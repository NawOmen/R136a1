_ABBREVIATIONS = dict(zip(("цфо", "пфо", "сзфо", "урфо", "юфо", "сфо", "скфо", "дфо"), _DISTRICTS))
_ALIASES = {
    "кемеровская область": "кемеровская область - кузбасс",
    "ханты-мансийский автономный округ": "ханты-мансийский автономный округ - югра",
}


def normalize_region(value: str) -> str:
    value = re.sub(r"^(?:город\s+|г\.\s*|г\s+)", "", value.strip().lower()).replace("ё", "е")
    value = re.sub(r"\s*[—–]\s*", " - ", value)
    value = " ".join(value.strip(" .").split())
    return _ALIASES.get(value, value)


_MEMBERS = {district: {normalize_region(region) for region in regions.split("|")} for district, regions in _DISTRICTS.items()}
_RUSSIAN_REGIONS = set().union(*_MEMBERS.values()) | {
    "донецкая народная республика", "луганская народная республика", "запорожская область", "херсонская область",
}


def region_is_served(advertised: list[str], destination: str) -> bool:
    target = normalize_region(destination)
    for value in advertised:
        region = normalize_region(value)
        if region == target and target:
            return True
        if region in {"россия", "рф", "российская федерация"} and target in _RUSSIAN_REGIONS:
            return True
        district = _ABBREVIATIONS.get(region, region.removesuffix(" федеральный округ").removesuffix(" фо"))
        if target in _MEMBERS.get(district, set()):
            return True
    return False
