"""Reviewed platform facts. The model selects sources; published text is stored here."""
from pydantic import BaseModel, Field

class KnowledgeSelection(BaseModel):
    source_ids: list[str] = Field(default_factory=list, max_length=2)

RECORDS = {
    "purchase": ("Потребность и каталог", "/needs/new", "Покупатель может найти товар в каталоге или создать потребность. Ручное создание бесплатно. Перед публикацией проверьте требования, объём, бюджет в рублях и срок. Разбор материалов агентом доступен в двух пробных сценариях при включённом лимите."),
    "company": ("Компания и права", "/dashboard", "Один аккаунт может покупать и продавать от имени компаний в пределах выданных прав. Публикация и сделки требуют проверки компании. Режим работы не добавляет серверных полномочий."),
    "deal": ("Согласование и исполнение", "/deals", "Предложение не становится сделкой автоматически. Критичные действия подтверждает человек. Цена, распределение объёма и резервы рассчитываются программным кодом; помощник не принимает финансовых решений. Исполнение, отгрузка и приёмка доступны в разделе сделок."),
    "support": ("Поддержка", "/support", "Напишите сообщение в чат поддержки. Переписка и ответы сотрудника сохраняются в чате, о новых ответах приходят уведомления. Исходные файлы, пароли и секреты автоматически не прикладываются."),
}

def answer(selection):
    ids = selection.source_ids
    if not ids or any(key not in RECORDS for key in ids):
        return {"answer": "В проверенной справке нет ответа на этот вопрос. Обратитесь в поддержку.", "links": ["/support"]}
    ids = list(dict.fromkeys(ids))
    return {"answer": "\n\n".join(RECORDS[key][2] for key in ids), "links": [RECORDS[key][1] for key in ids]}
